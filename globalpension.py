@st.cache_data(ttl=3600)
def fetch_google_news(query, lang="en", max_items=12):
    """Google News RSS 검색 (API 키 불필요). lang: 'en' 또는 'ko'"""
    import xml.etree.ElementTree as ET
    from urllib.parse import quote
    if lang == "ko":
        url = f"https://news.google.com/rss/search?q={quote(query)}&hl=ko&gl=KR&ceid=KR:ko"
    else:
        url = f"https://news.google.com/rss/search?q={quote(query)}&hl=en-US&gl=US&ceid=US:en"
    articles = []
    try:
        resp = requests.get(url, timeout=10, headers={"User-Agent": "Mozilla/5.0"})
        if resp.status_code != 200:
            return articles
        root = ET.fromstring(resp.content)
        for item in root.findall(".//item")[:max_items]:
            source = (item.findtext("source") or "Google News").strip()
            title  = clean_html((item.findtext("title") or "").strip())
            # 제목 끝 " - 출처명" 중복 제거 (출처는 별도 배지로 표시)
            if source and title.endswith(f"- {source}"):
                title = title[: title.rfind(f"- {source}")].rstrip(" -–")
            desc   = clean_html((item.findtext("description") or "").strip())
            link   = (item.findtext("link") or "").strip()
            articles.append({
                "title":       title[:150],
                "description": desc[:400],
                "link":        link,
                "pubDate":     item.findtext("pubDate", ""),
                "source":      source,
                "is_global":   lang != "ko",
            })
    except Exception:
        pass
    return articles

